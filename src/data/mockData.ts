// Helper functions
export function getSellerById(id: string): SellerProfile | undefined {
  return mockSellers.find(s => s._id === id);
}

export function getMenuItemsBySeller(sellerId: string): MenuItem[] {
  return mockMenuItems.filter(m => m.sellerId === sellerId);
}

export function getSellersByType(type: SellerType | 'all'): SellerProfile[] {
  if (type === 'all') return mockSellers;
  return mockSellers.filter(s => s.type === type);
}

export function searchMenuItems(query: string): MenuItem[] {
  const lowerQuery = query.toLowerCase();
  return mockMenuItems.filter(
    m =>
      m.name.toLowerCase().includes(lowerQuery) ||
      m.description.toLowerCase().includes(lowerQuery) ||
      m.tags.some(t => t.toLowerCase().includes(lowerQuery))
  );
}
